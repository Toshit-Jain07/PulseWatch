package com.toshit.PulseWatch.controller;

import com.toshit.PulseWatch.dto.request.LoginRequest;
import com.toshit.PulseWatch.dto.request.RegisterRequest;
import com.toshit.PulseWatch.dto.response.AuthResponse;
import com.toshit.PulseWatch.services.AuthService;
import jakarta.validation.Valid;
import lombok.RequiredArgsConstructor;
import org.springframework.http.ResponseEntity;
import org.springframework.web.bind.annotation.PostMapping;
import org.springframework.web.bind.annotation.RequestBody;
import org.springframework.web.bind.annotation.RequestMapping;
import org.springframework.web.bind.annotation.RestController;

@RestController     //handles HTTP requests, and every method's return
                    //value should be serialized to JSON in the response body
@RequestMapping("/auth")
@RequiredArgsConstructor
public class AuthController {

    private final AuthService authService; //constructor generated by ReqArgscontr

    @PostMapping("/register")
    public ResponseEntity<AuthResponse> register(@Valid @RequestBody RegisterRequest request) {
        AuthResponse response = authService.register(request);
        return ResponseEntity.ok(response); //https status code 200 Success
    }

    @PostMapping("/login")
    public ResponseEntity<AuthResponse> login(@Valid @RequestBody LoginRequest request) {
        AuthResponse response = authService.login(request);
        return ResponseEntity.ok(response);
    }
}